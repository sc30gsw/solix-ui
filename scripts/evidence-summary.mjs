export const evidenceDirectory = "docs/verification";
export const fullReportFile = "README.md";
export const summaryFile = "SUMMARY.md";
export const commentSizeLimit = 65_536;
export const scriptsLine = "The scripts are in `.agents/skills/verify-playground/scripts`.";

const localImage = /\]\((?!https?:)([^)]+\.(?:png|gif))\)/g;

function row(cells) {
  return `| ${cells.join(" | ")} |`;
}

function table(headings, rows) {
  return [row(headings), row(headings.map(() => "---")), ...rows.map(row)].join("\n");
}

function inCell(text) {
  return String(text).replaceAll("|", "\\|").replaceAll("\n", " ");
}

export function reportHeading(facts) {
  return [
    "# Verification evidence",
    "Generated by `vp run evidence`. Do not edit by hand.",
    ["| | |", "| --- | --- |", ...facts.map(row)].join("\n"),
  ];
}

export function diagnosticsSection(upstreamExceptions) {
  const heading = "## Solid development diagnostics";
  if (upstreamExceptions.length === 0) {
    return [heading, "Solid's development build reported no diagnostics at all."];
  }
  return [
    heading,
    "Solid's development build reported no diagnostics from this project's code. It did report these, which come from a dependency and are accepted until the date shown:",
    table(
      ["Diagnostic", "Raised by", "Reached through", "Why", "Accepted until"],
      upstreamExceptions.map(({ code, package: from, reachedThrough, reason, expires }) => [
        `\`${code}\``,
        from,
        reachedThrough,
        reason,
        expires,
      ]),
    ),
  ];
}

function resultCell(run) {
  if (run === undefined) return "not driven";
  const failures = run.observations.filter(({ pass }) => !pass);
  const count = `${run.observations.length - failures.length} of ${run.observations.length} passed`;
  if (failures.length === 0) return `[${count}](${run.recording})`;
  const failed = failures.map(({ what }) => inCell(what)).join("; ");
  return `[FAIL, ${count}](${run.recording}). Failed: ${failed}`;
}

export function evidenceSummary({ facts, engines, journeys, upstreamExceptions }) {
  return `${[
    ...reportHeading(facts),
    "## How this was verified",
    "`vp check --deny-warnings`, `vp run lint:solid` and `vp test` passed. `launch.sh` built the library and the app in production mode and served them, `doctor.sh` confirmed the server came from this checkout and this build, `drive.mjs` drove each journey below in each installed browser engine as a user would and recorded it, and `cleanup.sh` stopped the server.",
    scriptsLine,
    "## Journeys",
    "Each cell counts the observations that passed in that engine and links to the recording of the journey.",
    table(
      ["Journey", ...engines],
      journeys.map(({ title, runs }) => [
        inCell(title),
        ...engines.map((engine) => resultCell(runs[engine])),
      ]),
    ),
    ...diagnosticsSection(upstreamExceptions),
  ].join("\n\n")}\n`;
}

export function evidenceMarker(headCommit) {
  return `<!-- verification-evidence:${headCommit} -->`;
}

export function evidenceComment({ summary, repository, evidenceCommit, evidenceRef, headCommit }) {
  const atEvidenceCommit = `https://github.com/${repository}/blob/${evidenceCommit}/${evidenceDirectory}`;
  return [
    evidenceMarker(headCommit),
    `Recorded by CI for ${headCommit.slice(0, 7)}. The evidence is kept outside every branch, under \`${evidenceRef}\`. Every step, screenshot and observed value is in [the full report](${atEvidenceCommit}/${fullReportFile}).`,
    "",
    summary.replace(localImage, `](${atEvidenceCommit}/$1?raw=true)`),
  ].join("\n");
}
