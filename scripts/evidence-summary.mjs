export const evidenceDirectory = "docs/verification";
export const fullReportFile = "README.md";
export const summaryFile = "SUMMARY.md";
export const recordingFile = "recording.gif";
export const commentSizeLimit = 65_536;

const scriptsLine = "The scripts are in `.agents/skills/verify-playground/scripts`.";
const verificationSteps = [
  "1. `vp check --deny-warnings`, `vp run lint:solid` and `vp test` ran and passed. The tests include the app on Solid's development build, generated style definitions, generated consumer props for each component, and generated modal sequences of presses, keys and typing.",
  "2. `launch.sh` built the library and the app in production mode and started the built server.",
  "3. `doctor.sh` confirmed the running instance came from this checkout and this build.",
  "4. `drive.mjs` drove each journey below in each installed browser engine, as a user would, and recorded it.",
  "5. `cleanup.sh` stopped the server.",
].join("\n");
const condensedSteps =
  "`vp check --deny-warnings`, `vp run lint:solid` and `vp test` passed. `launch.sh` built the library and the app in production mode and served them, `doctor.sh` confirmed the server came from this checkout and this build, `drive.mjs` drove each journey in each installed browser engine as a user would and recorded it, and `cleanup.sh` stopped the server.";
const atxHeading = /^(#{1,6})[ \t]+(.+?)[ \t]*$/gm;
const removedFromAnchors = /[^\p{L}\p{M}\p{N}\p{Pc} -]/gu;
const relativeLink = /\]\((?![a-z][a-z\d+.-]*:)([^)\s]+)\)/g;
const journeyHeadingLevel = 2;

export function runDirectory(engine, journey) {
  return `${engine}/${journey}`;
}

function row(cells) {
  return `| ${cells.join(" | ")} |`;
}

function table(headings, rows) {
  return [row(headings), row(headings.map(() => "---")), ...rows.map(row)].join("\n");
}

function inCell(text) {
  return String(text).replaceAll("|", "\\|").replaceAll("\n", " ");
}

function uniqueAnchor(slug, occurrences) {
  let anchor = slug;
  while (occurrences.has(anchor)) {
    occurrences.set(slug, occurrences.get(slug) + 1);
    anchor = `${slug}-${occurrences.get(slug)}`;
  }
  occurrences.set(anchor, 0);
  return anchor;
}

export function headingAnchors(markdown) {
  const occurrences = new Map();
  return [...markdown.matchAll(atxHeading)].map(([, hashes, text]) => ({
    level: hashes.length,
    text,
    anchor: uniqueAnchor(
      text.toLowerCase().replace(removedFromAnchors, "").replaceAll(" ", "-"),
      occurrences,
    ),
  }));
}

function reportHeading(facts) {
  return [
    "# Verification evidence",
    "Generated by `vp run evidence`. Do not edit by hand.",
    ["| | |", "| --- | --- |", ...facts.map(row)].join("\n"),
  ];
}

function diagnosticsSection(upstreamExceptions) {
  const heading = "## Solid development diagnostics";
  if (upstreamExceptions.length === 0) {
    return [heading, "Solid's development build reported no diagnostics at all."];
  }
  return [
    heading,
    "Solid's development build reported no diagnostics from this project's code. It did report these, which come from a dependency and are accepted until the date shown:",
    table(
      ["Diagnostic", "Raised by", "Reached through", "Why", "Accepted until"],
      upstreamExceptions.map(({ code, package: from, reachedThrough, reason, expires }) => [
        `\`${code}\``,
        from,
        reachedThrough,
        reason,
        expires,
      ]),
    ),
  ];
}

function runSection(engine, journey, title, { browserVersion, steps, observations }) {
  const directory = runDirectory(engine, journey);
  const numberedSteps = steps.map(
    ({ description, image }, index) =>
      `${index + 1}. ${description}\n\n   ![Screenshot of step ${index + 1}](${directory}/${image})`,
  );
  return [
    `### ${engine} ${browserVersion}`,
    "Recording of the whole journey:",
    `![Recording of ${title} in ${engine}](${directory}/${recordingFile})`,
    "Steps:",
    numberedSteps.join("\n\n"),
    "Observed:",
    table(
      ["What", "Expected", "Observed", "Result"],
      observations.map(({ what, expected, actual, pass }) => [
        what,
        `\`${JSON.stringify(expected)}\``,
        `\`${JSON.stringify(actual)}\``,
        pass ? "pass" : "FAIL",
      ]),
    ),
  ].join("\n\n");
}

function fullReport({ facts, engines, journeys, upstreamExceptions }) {
  return `${[
    ...reportHeading(facts),
    "## How this was verified",
    verificationSteps,
    scriptsLine,
    ...diagnosticsSection(upstreamExceptions),
    ...journeys.map(({ journey, title, runs }) =>
      [
        `## ${title}`,
        `Journey \`${journey}\`.`,
        ...engines.map((engine) => runSection(engine, journey, title, runs[engine])),
      ].join("\n\n"),
    ),
  ].join("\n\n")}\n`;
}

function resultCell(run) {
  if (run === undefined) return "not driven";
  const failures = run.observations.filter(({ pass }) => !pass);
  if (failures.length === 0) return `${run.observations.length} of ${run.observations.length}`;
  return `FAIL: ${failures.map(({ what }) => inCell(what)).join("; ")}`;
}

function summary({ facts, engines, journeys, upstreamExceptions }, journeyAnchors) {
  return `${[
    ...reportHeading(facts),
    "## How this was verified",
    condensedSteps,
    scriptsLine,
    "## Journeys",
    `Each journey links to its section of ${fullReportFile}, the full report, which holds its steps, screenshots, recordings and observed values. Each cell counts the observations that passed in that engine, or names those that failed.`,
    table(
      ["Journey", ...engines],
      journeys.map(({ title, runs }, index) => [
        `[${inCell(title)}](${fullReportFile}#${journeyAnchors[index]})`,
        ...engines.map((engine) => resultCell(runs[engine])),
      ]),
    ),
    ...diagnosticsSection(upstreamExceptions),
  ].join("\n\n")}\n`;
}

export function evidenceReports(evidence) {
  const full = fullReport(evidence);
  const journeyHeadings = headingAnchors(full)
    .filter(({ level }) => level === journeyHeadingLevel)
    .slice(-evidence.journeys.length);
  const journeyAnchors = evidence.journeys.map(({ title }, index) => {
    const heading = journeyHeadings[index];
    if (heading?.text !== title.trim()) {
      throw new Error(`${fullReportFile} has no heading "## ${title}" for the summary to link.`);
    }
    return heading.anchor;
  });
  return { fullReport: full, summary: summary(evidence, journeyAnchors) };
}

export function evidenceMarker(headCommit) {
  return `<!-- verification-evidence:${headCommit} -->`;
}

export function evidenceComment({ summary, repository, evidenceCommit, evidenceRef, headCommit }) {
  const atEvidenceCommit = `https://github.com/${repository}/blob/${evidenceCommit}/${evidenceDirectory}`;
  return [
    evidenceMarker(headCommit),
    `Recorded by CI for ${headCommit.slice(0, 7)}. The evidence is kept outside every branch, under \`${evidenceRef}\`. Every step, screenshot, recording and observed value is in [the full report](${atEvidenceCommit}/${fullReportFile}).`,
    "",
    summary.replace(relativeLink, `](${atEvidenceCommit}/$1)`),
  ].join("\n");
}
